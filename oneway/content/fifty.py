BY_NO: Dict[int, Belief] = {b.no: b for b in BELIEFS}
BY_SLUG: Dict[str, Belief] = {b.slug: b for b in BELIEFS}


def get(no: int) -> Belief:
    if no not in BY_NO:
        raise ValueError(f"1~50 범위를 벗어났습니다: {no}")
    return BY_NO[no]


def by_topic(topic: str) -> List[Belief]:
    return [b for b in BELIEFS if topic in b.topics]


def search(word: str) -> List[Belief]:
    """제목·키워드·본문에서 단어를 찾는다 (사이트 내 검색용)."""
    w = word.strip()
    if not w:
        return []
    hits = []
    for b in BELIEFS:
        haystack = " ".join([b.title, b.seo_title, b.description,
                             " ".join(b.keywords), " ".join(b.body)])
        if w in haystack:
            hits.append(b)
    return hits


