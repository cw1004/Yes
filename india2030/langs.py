PACKS: Dict[str, Dict] = {"ko": KO_PACK, "hi": HI_PACK}
LANGUAGES = tuple(PACKS)


def get_pack(lang: str) -> Dict:
    if lang not in PACKS:
        raise ValueError(f"지원하지 않는 언어: {lang} (가능: {', '.join(LANGUAGES)})")
    return PACKS[lang]


def title_for(no: int, lang: str) -> str:
    return get_pack(lang)["titles"][no - 1]
