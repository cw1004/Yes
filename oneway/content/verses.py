@dataclass(frozen=True)
class Verse:
    """성경의 한 대목을 가리키는 주소 + 우리가 풀어 쓴 한 줄."""
    key: str
    book: str          # 가톨릭 약칭
    where: str         # "11,28" 형식
    gist: str          # 자체 표현 (번역문 인용 아님)
    tags: tuple = ()

    @property
    def ref(self) -> str:
        """가톨릭식 표기 — 마태 11,28"""
        return f"{self.book} {self.where}"

    @property
    def ref_protestant(self) -> str:
        """개신교식 표기 — 마태복음 11:28"""
        name = BOOK_ALIASES.get(self.book, self.book)
        return f"{name} {self.where.replace(',', ':')}"

    @property
    def neutral(self) -> str:
        """어느 쪽 표기를 쓰는 사람이든 찾을 수 있게, 라벨 없이 둘 다.

        "(개신교 표기: …)" 라고 써 붙이는 순간 그 페이지는 교파 이야기가 된다.
        처음 온 사람에게는 그것부터 보이면 안 된다.
        """
        return f"{self.ref} · {self.ref_protestant}"

    @property
    def both(self) -> str:
        """교파를 **직접 물었을 때만** 쓰는, 라벨이 붙은 표기."""
        return f"{self.ref} (개신교 표기: {self.ref_protestant})"


def _v(key, book, where, gist, *tags) -> Verse:
    return Verse(key=key, book=book, where=where, gist=gist, tags=tuple(tags))


