@dataclass(frozen=True)
class Episode:
    no: int
    title: str
    act: Act
    director_note: Optional[str] = None
    no_spoiler: bool = False
    cliffhanger: bool = False

    @property
    def slug(self) -> str:
        return f"ep{self.no:03d}"

    @property
    def act_no(self) -> int:
        return self.act.no


def act_for(no: int) -> Act:
    for act in ACTS:
        if act.first <= no <= act.last:
            return act
    raise ValueError(f"{no}화에 해당하는 ACT가 없습니다 (1~100)")


def get_episode(no: int) -> Episode:
    if not 1 <= no <= 100:
        raise ValueError(f"화수는 1~100 사이여야 합니다: {no}")
    return Episode(
        no=no,
        title=TITLES[no - 1],
        act=act_for(no),
        director_note=DIRECTOR_NOTES.get(no),
        no_spoiler=no in NO_SPOILER,
        cliffhanger=no in CLIFFHANGER,
    )


def all_episodes() -> List[Episode]:
    return [get_episode(n) for n in range(1, 101)]


def parse_range(spec: str) -> List[int]:
    """'1-100', '3', '1-5,20,44-46' 형식을 화수 리스트로 변환."""
    out: List[int] = []
    for chunk in str(spec).split(","):
        chunk = chunk.strip()
        if not chunk:
            continue
        if "-" in chunk:
            a, b = chunk.split("-", 1)
            a, b = int(a), int(b)
            if a > b:
                a, b = b, a
            out.extend(range(a, b + 1))
        else:
            out.append(int(chunk))
    seen, uniq = set(), []
    for n in out:
        if n in seen:
            continue
        if not 1 <= n <= 100:
            raise ValueError(f"화수는 1~100 사이여야 합니다: {n}")
        seen.add(n)
        uniq.append(n)
    return uniq
