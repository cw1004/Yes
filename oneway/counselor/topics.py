BY_KEY: Dict[str, Topic] = {t.key: t for t in TOPICS}

# 기본 주제 — 무엇에도 걸리지 않을 때 (분류 실패를 사용자에게 들키지 않게 한다)
DEFAULT_KEY = "입문"


def get(key: str) -> Topic:
    return BY_KEY[key]


def classify(text: str, limit: int = 2) -> List[Tuple[Topic, int]]:
    """입력에서 주제를 점수순으로 찾는다.

    형태소 분석기 없이 동작해야 하므로 단순 포함 검사 + 가중치를 쓴다.
    외부 의존성 없이도 실무에서 충분히 쓸 만한 정확도가 나온다.
    """
    text = (text or "").strip()
    if not text:
        return []
    scored: List[Tuple[Topic, int]] = []
    for t in TOPICS:
        score = sum(3 for cue in t.cues if cue in text)
        if score:
            scored.append((t, score * t.weight))
    scored.sort(key=lambda p: (-p[1], -p[0].weight, p[0].key))
    return scored[:limit]


def best(text: str) -> Topic:
    hits = classify(text, limit=1)
    return hits[0][0] if hits else get(DEFAULT_KEY)
