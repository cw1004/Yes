from dataclasses import dataclass, field
from typing import Dict, List, Optional


@dataclass(frozen=True)
class Belief:
    no: int
    slug: str
    title: str            # 사이트 안에서 쓰는 제목
    seo_title: str        # 검색 결과에 노출되는 제목 (질문형)
    description: str      # 메타 설명 (검색 결과 요약문)
    keywords: tuple
    body: tuple           # 본문 문단들
    verses: tuple         # verses.py 의 key
    question: str         # 오늘의 질문
    prayer: str           # 30초 기도
    practice: str         # 오늘의 한 걸음
    topics: tuple = ()    # 상담 주제 연결 키 (counselor/topics.py)

    @property
    def url(self) -> str:
        return f"/believe/{self.no:02d}-{self.slug}"

    @property
    def group(self) -> "Group":
        return group_of(self.no)


@dataclass(frozen=True)
class Group:
    no: int
    first: int
    last: int
    name: str
    subtitle: str


