BY_KEY: Dict[str, Verse] = {v.key: v for v in VERSES}


def get(key: str) -> Verse:
    try:
        return BY_KEY[key]
    except KeyError:
        raise KeyError(f"등록되지 않은 구절 키: {key}")


def by_tag(tag: str) -> List[Verse]:
    return [v for v in VERSES if tag in v.tags]


def pick(keys: List[str], used: Optional[set] = None) -> Verse:
    """같은 대화에서 같은 구절을 반복하지 않도록 아직 안 쓴 것을 먼저 고른다."""
    used = used or set()
    for k in keys:
        if k not in used:
            return get(k)
    return get(keys[0])
