BY_SLUG: Dict[str, Entry] = {e.slug: e for e in ENTRIES}


def get(slug: str) -> Entry:
    if slug not in BY_SLUG:
        raise KeyError(f"없는 입구입니다: {slug}")
    return BY_SLUG[slug]


def for_topic(topic: str) -> List[Entry]:
    return [e for e in ENTRIES if topic in e.topics]
